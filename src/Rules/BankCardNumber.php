    public function validate(string $attribute, mixed $value, Closure $fail): void
    {
        $card = app(JalaliConverter::class)->toLatinDigits((string) $value);
        $card = preg_replace('/[\s\-]/', '', $card);

        if (! preg_match('/^\d{16}$/', $card)) {
            $fail('شماره کارت باید ۱۶ رقم باشد.');
            return;
        }

        // چک تکراری بودن
        if (preg_match('/^(\d)\1{15}$/', $card)) {
            $fail('شماره کارت وارد شده معتبر نیست.');
            return;
        }

        // تشخیص بانک
        $bank = self::detectBank($card);
        if ($bank === null) {
            $fail('شماره کارت وارد شده به هیچ بانک ایرانی تعلق ندارد.');
        }
    }

    /**
     * تشخیص بانک از روی شماره کارت.
     */
    public static function detectBank(string $card): ?string
    {
        $card = preg_replace('/[\s\-]/', '', $card);
        if (strlen($card) !== 16) {
            return null;
        }

        $prefix = substr($card, 0, 6);
        return self::BANK_PREFIXES[$prefix] ?? null;
    }
